	/** Syncs data from the engine to the lights. */
	syncLights() {
		const { shift } = this.controllerState;
		for (let n = 1; n <= 4; n++) this.updateButtonLight("main", `fx${n}`, shift ? this.config[`fxButton${n}ShiftPush`] : this.config[`fxButton${n}Push`], this.config.colorTheme);
		this.updateButtonLight("main", "fxFilter", this.config.filterButtonPush, this.config.colorFx5);
		for (const group of ["left", "right"]) {
			const engineGroup = this.getEngineGroup(group);
			this.updateButtonLight(group, "eqModeSwitch", shift ? this.config.eqModeButtonShiftPush : this.config.eqModeButtonPush, this.config.colorEqSwitch);
			this.updateButtonLight(group, "stemModeSwitch", shift ? this.config.stemModeButtonShiftPush : this.config.stemModeButtonPush, this.config.colorStemsSwitch);
			this.updateButtonLight(group, "fxToggle", shift ? this.config.fxToggleShiftPush : this.config.fxTogglePush, defaultedColor(this.config.colorTheme, DEFAULT_Z1_MK2_CONFIG.colorTheme));
			this.updateButtonLight(group, "prelisten", shift ? this.config.prelistenToggleShiftPush : this.config.prelistenTogglePush, this.config.colorPrelistenToggle);
			this.controller.lights.setVuValue(group, engine.getValue(engineGroup, "VuMeter") * 10);
			const isBeatActive = engine.getValue(engineGroup, "beat_active") !== 0;
			for (let n = 1; n <= 6; n++) {
				const colorKey = `colorBottomLeds${n}`;
				if (!(colorKey in this.config)) throw new Error("Invalid color index");
				let color = defaultedColor(defaultedColor(defaultedColor(this.config[colorKey], this.config.colorBottomLedsDefault), this.config.colorTheme), DEFAULT_Z1_MK2_CONFIG.colorTheme);
				if (this.config.endWarning && engine.getValue(engineGroup, "end_of_track") === 1) color = dimColorWhen(this.config.colorEndWarning, !isBeatActive);
				if (this.config.activeLoop && engine.getValue(engineGroup, "loop_enabled")) color = this.config.colorActiveLoop;
				if (this.config.blinkBottomLeds) color = dimColorWhen(color, !isBeatActive);
				this.controller.lights.setColoredLight(group, `bottomLed${n}`, color);
			}
		}
		this.controller.lights.send();
	}
