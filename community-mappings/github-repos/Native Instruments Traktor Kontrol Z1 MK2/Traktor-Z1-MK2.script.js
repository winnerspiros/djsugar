	incomingData(data, _length) {
		this.controller.processInput(data);
		this.handleInput();
		this.syncLights();
		this.syncScreens();
	}
	shutdown() {
		if (this.lightsTimer) {
			engine.stopTimer(this.lightsTimer);
			this.lightsTimer = void 0;
		}
		this.controller.lights.clear();
		this.controller.lights.send();
		for (const screen of Object.values(this.screens)) {
			screen.clear();
			screen.send(this.isDebugging);
		}
	}
	/** Toggles the value of an engine boolean. */
	toggleEngineBoolean(group, name) {
		const value = engine.getValue(group, name);
		engine.setValue(group, name, value === 0 ? 1 : 0);
	}
	/**
	* Scales a controller value between 0-1 into an engine value using the
	* specified algorithm.
	*/
	scaleValue(value, scale) {
		switch (scale) {
			case "flat": return value;
			case "gain":
 /**
			* Scales a value from 0-1 into a value from 0-4, for use as a gain value. Values < 0.5 are
			* linearly mapped to 0-1, and 0.5-1 are mapped to 1-4. */
			if (value < .5) return value * 2;
			else return (value - .5) * 6 + 1;
			case "crossfader":
 /** Scales a value from 0-1 into a value from -1-1 for use as a crossfader value. */
			return value * 2 - 1;
		}
	}
	/** Converts engine gain value back into a number between 0 and 1. */
	unscaleGain(value) {
		if (value < 1) return value / 2;
		else return (value - 1) / 6 + .5;
	}
	unscaleValue(value, scale) {
		switch (scale) {
			case "flat": return value;
			case "gain": return this.unscaleGain(value);
			case "crossfader": return (value + 1) / 2;
		}
	}
	/** Formats a numerical value for display on a screen */
	formatValueForScreen(value, format) {
		switch (format) {
			case "signed": {
				const scaled = Math.round(Math.abs(value - .5) * 100);
				return value > .5 || scaled === 0 ? `${scaled}` : `-${scaled}`;
			}
			case "unsigned": return `${Math.round(value * 100)}%`;
		}
	}
	syncKnobToEngine({ controllerGroup, controllerKnobName, engineGroup, engineName, label, format, scale, showValueScreen = false, softTakeover = false, unmapped = false }) {
		const value = this.controller.getKnobIfChanged(controllerGroup, controllerKnobName);
		if (value === void 0) return;
		if (softTakeover) {
			const existingValue = this.unscaleValue(engine.getValue(engineGroup, engineName), scale);
			if (Math.abs(existingValue - value) > SOFT_TAKEOVER_MARGIN) {
				this.screenStatuses[controllerGroup] = {
					kind: "softTakeover",
					value,
					target: existingValue,
					format,
					label
				};
				this.scheduleScreenReset(controllerGroup, SCREEN_RESET_MS);
				this.syncScreens();
				return;
			} else if (this.screenStatuses[controllerGroup]?.kind === "softTakeover") {
				this.screenStatuses[controllerGroup] = { kind: "home" };
				this.syncScreens();
			}
		}
		const scaledValue = this.scaleValue(value, scale);
		if (!unmapped) engine.setValue(engineGroup, engineName, scaledValue);
		if (this.isDebugging) console.debug(`Synced knob ${controllerGroup}.${controllerKnobName} with value ${value} to engine ${engineGroup}.${engineName} value ${scaledValue}`);
		if (showValueScreen) {
			this.screenStatuses[controllerGroup] = {
				kind: "value",
				label,
				value: this.formatValueForScreen(value, format)
			};
			this.scheduleScreenReset(controllerGroup, SCREEN_RESET_MS);
			this.syncScreens();
		}
	}
	/** Gets the engine group which currently corresponds to a controller group. */
	getEngineGroup(group) {
		switch (group) {
			case "main": return "[Master]";
			case "left": return this.controllerState.decksToggle.left ? "[Channel3]" : "[Channel1]";
			case "right": return this.controllerState.decksToggle.right ? "[Channel4]" : "[Channel2]";
		}
	}
