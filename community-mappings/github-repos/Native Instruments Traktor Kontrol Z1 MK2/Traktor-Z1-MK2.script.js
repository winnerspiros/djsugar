	/** Sync data to controller screens */
	syncScreens() {
		for (const group of [
			"main",
			"left",
			"right"
		]) {
			const screen = this.screens[group];
			const status = this.screenStatuses[group];
			switch (status.kind) {
				case "value":
					this.drawValueScreen(screen, status);
					break;
				case "softTakeover":
					this.drawSoftTakeoverScreen(screen, status);
					break;
				case "home":
					if (group === "main") this.drawHomeScreen(screen);
					else if (this.controllerState.stemToggle[group]) this.drawStemScreen(screen, group);
					else this.drawEqScreen(this.screens[group], group);
					break;
			}
			screen.send(this.isDebugging);
		}
	}
